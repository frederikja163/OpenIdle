using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;

namespace Generator.Core;

public sealed class CsEmitter : IDtoEmitter
{
    private readonly ScopedTextWriter _textWriter;
    private readonly List<Object> _allObjects = new();

    public CsEmitter(TextWriter writer)
    {
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteLine("using System;");
        writer.WriteLine("using System.Text.Json.Serialization;");
        writer.WriteLine("using Backend.Services;");
        writer.WriteLine();
        writer.WriteLine("namespace Backend.Dtos;");
        writer.WriteLine();

        _textWriter = new ScopedTextWriter(writer);
    }

    public void EmitDtos(DtoModel model)
    {
        foreach (Object obj in model.AllObjects)
        {
            EmitClass(obj);
            _allObjects.Add(obj);
        }

        EmitEnums(model);

        EmitDropTableData(model);

        EmitActivityData(model);

        EmitToolData(model);
    }

    private void EmitEnums(DtoModel model)
    {
        foreach (Enum en in model.Enums.Values)
        {
            using (Scope _ = _textWriter.Scope($"public enum {en.Name.UpperCamelCase}"))
            {
                foreach (EnumValue item in en.GetEnums())
                {
                    _textWriter.WriteLine($"{item.Name.UpperCamelCase},");
                }
            }
        }
    }

    private void EmitDropTableData(DtoModel model)
    {
        _textWriter.WriteLine();
        using (Scope _ = _textWriter.Scope("public static class DropTableData"))
        {
            using (Scope __ = _textWriter.Scope("public static void AddAll(DropTableService service)"))
            {
                foreach (DropTable dropTable in model.DropTables.Values)
                {
                    EmitDropTable(dropTable);
                }
            }
        }
    }

    private void EmitActivityData(DtoModel model)
    {
        _textWriter.WriteLine();
        using (Scope _ = _textWriter.Scope("public static class ActivityData"))
        {
            using (Scope __ = _textWriter.Scope("public static void AddAll(ActivityService service)"))
            {
                foreach (Activity activity in model.Activities.Values)
                {
                    string rewards = string.Join(", ", activity.Rewards.Select(RewardExpression));
                    string requirements = string.Join(", ", activity.Requirements.Select(RequirementExpression));
                    string costs = string.Join(", ", activity.Costs.Select(ItemCostExpression));
                    _textWriter.WriteLine(
                        $"service.AddActivity(ActivityId.{activity.Name.UpperCamelCase}, new ActivityDefinition(time: {TimeLiteral(activity.Time)}, rewards: [{rewards}], requirements: [{requirements}], costs: [{costs}]));");
                }
            }
        }
    }

    private void EmitToolData(DtoModel model)
    {
        _textWriter.WriteLine();
        using (Scope _ = _textWriter.Scope("public static class ToolData"))
        {
            using (Scope __ = _textWriter.Scope("public static void AddAll(ToolService service)"))
            {
                foreach (Item item in model.Items.Values)
                {
                    string tags = string.Join(", ", item.Tags.Select(t => $"ItemTagId.{new Casing(t.Name).UpperCamelCase}"));
                    string stats = string.Join(", ", item.Stats.Select(ItemStatExpression));
                    _textWriter.WriteLine(
                        $"service.AddItem(ItemId.{item.Name.UpperCamelCase}, new ItemDefinition(tags: [{tags}], stats: [{stats}]));");
                }

                foreach (Skill skill in model.Skills.Values.Where(s => s.Slots.Count > 0))
                {
                    string slots = string.Join(", ", skill.Slots.Select(SlotExpression));
                    _textWriter.WriteLine(
                        $"service.AddSkillSlots(SkillId.{skill.Name.UpperCamelCase}, [{slots}]);");
                }
            }
        }
    }

    private static string ItemStatExpression(ItemStat stat)
    {
        return $"new ItemStat(ToolStat.{ItemStats.ByKey[stat.Name]}, {stat.Value.ToString(CultureInfo.InvariantCulture)}f)";
    }

    private static string SlotExpression(Slot slot)
    {
        return $"new SlotBinding(ItemSlotId.{new Casing(slot.Name).UpperCamelCase}, ItemTagId.{new Casing(slot.Tag.Name).UpperCamelCase}, {slot.Required.ToString().ToLowerInvariant()})";
    }

    private void EmitDropTable(DropTable dropTable)
    {
        _textWriter.Write($"service.AddDropTable(DropTableId.{dropTable.Name.UpperCamelCase}, new DropTable(");
        if (dropTable.Rewards.Count > 0)
        {
            _textWriter.WriteLine();
            using (Scope ___ = new(ScopeStyle.Indentation, _textWriter))
            {
                for (int i = 0; i < dropTable.Rewards.Count; i++)
                {
                    string separator = i < dropTable.Rewards.Count - 1 ? "," : "";
                    _textWriter.WriteLine($"{RewardExpression(dropTable.Rewards[i])}{separator}");
                }
            }
        }
        _textWriter.WriteLine("));");
    }

    private static string RewardExpression(Reward reward)
    {
        return reward switch
        {
            ItemReward itemReward =>
                $"new ItemReward({itemReward.Count}, {WeightLiteral(itemReward.Weight)}, ItemId.{new Casing(itemReward.Item).UpperCamelCase})",
            TableReward tableReward =>
                $"new TableReward({tableReward.Count}, {WeightLiteral(tableReward.Weight)}, DropTableId.{new Casing(tableReward.Table).UpperCamelCase})",
            XpReward xpReward =>
                $"new XpReward({xpReward.Count}, {WeightLiteral(xpReward.Weight)}, SkillId.{new Casing(xpReward.Skill).UpperCamelCase})",
            _ => throw new NotSupportedException("Reward expressions should drop a table, an item or xp."),
        };
    }

    private static string RequirementExpression(LevelRequirement requirement)
    {
        return $"new LevelRequirement(SkillId.{new Casing(requirement.Skill).UpperCamelCase}, {requirement.Count})";
    }

    private static string ItemCostExpression(ItemCost cost)
    {
        return $"new ItemCost({cost.Count}, ItemId.{new Casing(cost.Item).UpperCamelCase})";
    }

    private static string WeightLiteral(float? weight)
    {
        return weight is null ? "null" : weight.Value.ToString(CultureInfo.InvariantCulture) + "f";
    }

    private static string TimeLiteral(float time)
    {
        return time.ToString(CultureInfo.InvariantCulture) + "f";
    }

    private void EmitClass(Object obj)
    {
        using (Scope _ = _textWriter.Scope($"public sealed class {obj.Name.UpperCamelCase} : {BaseType(obj)}"))
        {
            foreach (Property property in obj.Properties)
            {
                Property(property);
            }
        }
        _textWriter.WriteLine();
    }

    private void Property(Property property, string setter = "init")
    {
        _textWriter.WriteLine($"[JsonPropertyName(\"{property.Name.LowerCamelCase}\")]");
        _textWriter.WriteLine($"{GetPropertyModifiers(property)} {GetPropertyType(property)} {property.Name.UpperCamelCase} {{ get; {setter}; }}");
    }

    private string GetPropertyModifiers(Property property)
    {
        string str = "public";
        if (!property.Optional)
        {
            str += " required";
        }

        return str;
    }

    private string BaseType(Object obj)
    {
        return obj switch
        {
            Dto => "DtoBase",
            Event => "EventBase",
            Request => "RequestBase",
            Response => "ResponseBase",
            _ => throw new ArgumentOutOfRangeException(nameof(obj))
        };
    }

    private string GetPropertyType(Property property)
    {
        if (property is CustomProperty custom)
        {
            string str = custom.Type.Name.UpperCamelCase;
            if (custom.Multiple)
                str += "[]";
            if (custom.Optional)
                str += "?";
            return str;
        }

        string builtIn = property.PropertyType switch
        {
            PropertyType.String => "string",
            PropertyType.Int => "int",
            PropertyType.Float => "float",
            PropertyType.Guid => "Guid",
            PropertyType.UserId => "Guid",
            PropertyType.ProfileId => "Guid",
            PropertyType.Timestamp => "long",
            _ => throw new ArgumentOutOfRangeException()
        };
        if (property.Multiple)
            builtIn += "[]";
        if (property.Optional)
            builtIn += "?";
        return builtIn;
    }

    public void Dispose()
    {
        _textWriter.WriteLine("[JsonPolymorphic]");
        foreach (Object obj in _allObjects)
        {
            _textWriter.WriteLine($"[JsonDerivedType(typeof({obj.Name.UpperCamelCase}), nameof({obj.Name.UpperCamelCase}))]");
        }
        using (Scope _ = _textWriter.Scope("public abstract class DtoBase"))
        {
        }
        _textWriter.WriteLine();
        using (Scope _ = _textWriter.Scope("public abstract class RequestBase : DtoBase"))
        {
            Property(new Property(PropertyType.Int, "int", "RequestId", false, true), "set");
        }
        _textWriter.WriteLine();
        using (Scope _ = _textWriter.Scope("public abstract class ResponseBase : DtoBase"))
        {
            Property(new Property(PropertyType.Int, "int", "RequestId", false, true), "set");
        }
        _textWriter.WriteLine();
        using (Scope _ = _textWriter.Scope("public abstract class EventBase : DtoBase"))
        {
            Property(new Property(PropertyType.Int, "int", "EventId", false, true), "set");
            Property(new Property(PropertyType.Timestamp, "long", "Timestamp", false, true), "set");
        }
        _textWriter.WriteLine();
    }
}